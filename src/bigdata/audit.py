"""J1 audit of MetroPT-3: hash, rows, columns, units, coverage, time-step distribution, duplicates, invalid rates."""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
import pandas as pd

from .config import load_config, resolve
from .acquire import sha256_file

UNITS = {  # per the MetroPT-3 dataset description (verify against the UCI page / Scientific Data paper)
    "TP2": "bar", "TP3": "bar", "H1": "bar", "DV_pressure": "bar", "Reservoirs": "bar",
    "Oil_temperature": "degC", "Motor_current": "A", "COMP": "digital 0/1", "DV_eletric": "digital 0/1",
    "Towers": "digital 0/1", "MPG": "digital 0/1", "LPS": "digital 0/1", "Pressure_switch": "digital 0/1",
    "Oil_level": "digital 0/1", "Caudal_impulses": "digital 0/1"}


def audit_metropt(csv_path: Path, cfg: dict) -> dict:
    ts_col = cfg["metropt"]["timestamp_col"]
    df = pd.read_csv(csv_path)
    df = df.drop(columns=[c for c in df.columns if c.startswith("Unnamed")])
    ts = pd.to_datetime(df[ts_col])
    dts = ts.sort_values().diff().dropna().dt.total_seconds()
    num = df.drop(columns=[ts_col]).select_dtypes("number")
    rep = {
        "file": str(csv_path), "sha256": sha256_file(csv_path), "bytes": csv_path.stat().st_size,
        "rows": len(df), "columns": list(df.columns), "units": {c: UNITS.get(c, "unknown") for c in num.columns},
        "time_start": str(ts.min()), "time_end": str(ts.max()), "is_sorted": bool(ts.is_monotonic_increasing),
        "dt_seconds_quantiles": {str(q): float(dts.quantile(q)) for q in (0.01, 0.1, 0.5, 0.9, 0.99, 1.0)},
        "dt_top_values": {str(k): int(v) for k, v in dts.round(3).value_counts().head(10).items()},
        "gaps_gt_60s": int((dts > 60).sum()), "largest_gap_s": float(dts.max()),
        "duplicate_rows": int(df.duplicated().sum()), "duplicate_timestamps": int(ts.duplicated().sum()),
        "nan_rate": {c: float(df[c].isna().mean()) for c in num.columns},
        "stats": {c: {"min": float(num[c].min()), "max": float(num[c].max()), "mean": float(num[c].mean())} for c in num.columns},
    }
    return rep


def write_report(rep: dict, out_md: Path, out_json: Path) -> None:
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(rep, indent=2))
    lines = ["# MetroPT-3 audit (generated by bigdata.audit)", "", f"- file: `{rep['file']}`", f"- SHA-256: `{rep['sha256']}`",
             f"- rows: {rep['rows']}, columns: {len(rep['columns'])}", f"- coverage: {rep['time_start']} -> {rep['time_end']}",
             f"- sorted by time: {rep['is_sorted']}", f"- duplicate rows: {rep['duplicate_rows']}, duplicate timestamps: {rep['duplicate_timestamps']}",
             f"- time-step quantiles (s): {rep['dt_seconds_quantiles']}", f"- most frequent steps (s): {rep['dt_top_values']}",
             f"- gaps > 60 s: {rep['gaps_gt_60s']} (largest {rep['largest_gap_s']:.0f} s)", "",
             "| column | unit | NaN rate | min | max | mean |", "|---|---|---|---|---|---|"]
    for c, u in rep["units"].items():
        s = rep["stats"][c]
        lines.append(f"| {c} | {u} | {rep['nan_rate'][c]:.4f} | {s['min']:.3f} | {s['max']:.3f} | {s['mean']:.3f} |")
    lines += ["", "Extreme values are NOT removed automatically (they may be the signal). Windowing assumes no duplicates; "
              "if `duplicate_rows` > 0 use the prepared (deduplicated) Parquet scope only."]
    out_md.write_text("\n".join(lines))


if __name__ == "__main__":
    cfg = load_config()
    m = json.loads((resolve(cfg, "manifests") / "metropt3.json").read_text())
    r = audit_metropt(Path(m["csv_path"]), cfg)
    write_report(r, Path(__file__).resolve().parents[2] / "docs" / "audit_metropt3.md", resolve(cfg, "manifests") / "metropt3_audit.json")
    print("audit written; duplicates:", r["duplicate_rows"])
